function FieldGroup({ className, ...props }: React.ComponentProps<"div">) {
  return (
    <div
      data-slot="field-group"
      // Nimbus alignment: `gap-3` between fields, the same step a dialog
      // body uses, so a console form stays as dense as the panels around it.
      className={cn(
        "group/field-group @container/field-group flex w-full flex-col gap-3 data-[slot=checkbox-group]:gap-3 *:data-[slot=field-group]:gap-4",
        className,
      )}
      {...props}
    />
  );
}

const fieldVariants = cva(
  "group/field flex w-full gap-2 data-[invalid=true]:text-destructive",
  {
    variants: {
      orientation: {
        vertical: "flex-col *:w-full [&>.sr-only]:w-auto",
        horizontal:
          "flex-row items-center has-[>[data-slot=field-content]]:items-start *:data-[slot=field-label]:flex-auto has-[>[data-slot=field-content]]:[&>[role=checkbox],[role=radio]]:mt-px",
        responsive:
          "flex-col *:w-full @md/field-group:flex-row @md/field-group:items-center @md/field-group:*:w-auto @md/field-group:has-[>[data-slot=field-content]]:items-start @md/field-group:*:data-[slot=field-label]:flex-auto [&>.sr-only]:w-auto @md/field-group:has-[>[data-slot=field-content]]:[&>[role=checkbox],[role=radio]]:mt-px",
        // Nimbus alignment: `inline` is a facet in a filter bar. The label
        // and its control share one line, and the field takes only the
        // width its content needs, so a wrapping toolbar holds several.
        inline: "w-auto flex-row items-center",
        // Nimbus alignment: `columns` is one row of an argument form. The
        // label sits in a 12rem column so the names and types of every row
        // line up, and the control column takes the rest.
        columns:
          "grid grid-cols-[minmax(0,12rem)_1fr] items-start *:data-[slot=field-label]:w-full *:data-[slot=field-label]:min-w-0 *:data-[slot=field-label]:pt-1.5 *:data-[slot=field-content]:min-w-0",
      },
    },
    defaultVariants: {
      orientation: "vertical",
    },
  },
);

function Field({
  className,
  orientation = "vertical",
  ...props
}: React.ComponentProps<"div"> & VariantProps<typeof fieldVariants>) {
  return (
    <div
      role="group"
      data-slot="field"
      data-orientation={orientation}
      className={cn(fieldVariants({ orientation }), className)}
      {...props}
    />
  );
}

