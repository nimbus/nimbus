/// High-level envelope keyring over a concrete local provider.
pub struct EnvelopeKeyring<'a> {
    provider: &'a dyn LocalKeyProvider,
    shred_registry: Arc<CryptoShredRegistry>,
}

impl<'a> EnvelopeKeyring<'a> {
    pub fn new(provider: &'a dyn LocalKeyProvider) -> Self {
        Self {
            provider,
            shred_registry: Arc::new(CryptoShredRegistry::new()),
        }
    }

    pub fn with_shred_registry(
        provider: &'a dyn LocalKeyProvider,
        shred_registry: Arc<CryptoShredRegistry>,
    ) -> Self {
        Self {
            provider,
            shred_registry,
        }
    }

    pub fn shred_registry(&self) -> Arc<CryptoShredRegistry> {
        self.shred_registry.clone()
    }

    pub fn generate_materials(
        &self,
        subject: &LocalKeySubject,
        cipher: ManifestCipher,
    ) -> Result<CryptoMaterials> {
        let generation = self
            .shred_registry
            .acquire_generation(subject)
            .map_err(map_shred_error)?;
        let header = key_manifest_header(subject, self.provider.kind(), cipher);
        let provider_identity = ProviderIdentity::from_kind(&header.key_provider);
        let mut trace = KeyringTrace::default();
        let generated = match self.provider.generate_data_key(subject, &header) {
            Ok(generated) => generated,
            Err(error) => {
                trace.push(trace_event(
                    "generate",
                    provider_identity,
                    subject,
                    generation,
                    Some(ProviderFailureKind::classify(&error)),
                ));
                return Err(map_key_provider_error(error));
            }
        };
        let manifest = KeyManifest {
            header,
            wrapped_key: generated.wrapped().clone(),
        };
        let provider = ProviderIdentity::from_kind(&manifest.header.key_provider);
        trace.push(trace_event(
            "generate",
            provider.clone(),
            subject,
            generation,
            None,
        ));
        let commitment =
            CommitmentMetadata::new(&manifest.header, &manifest.wrapped_key, generation);
        Ok(CryptoMaterials {
            suite: AlgorithmSuite::from_manifest_cipher(cipher),
            template: DekTemplate::for_manifest_cipher(cipher),
            subject_descriptor: subject.descriptor(),
            provider,
            commitment,
            manifest,
            trace,
            data_key: RevocableDataKey::new(
                generated.into_plaintext(),
                subject,
                generation,
                self.shred_registry.clone(),
            ),
        })
    }

    pub fn open_materials(
        &self,
        manifest: &KeyManifest,
        subject: &LocalKeySubject,
        expected_cipher: ManifestCipher,
        protected_path: &Path,
    ) -> Result<CryptoMaterials> {
        validate_manifest(
            manifest,
            self.provider,
            subject,
            expected_cipher,
            protected_path,
        )?;
        let generation = self
            .shred_registry
            .acquire_generation(subject)
            .map_err(map_shred_error)?;
        let provider = ProviderIdentity::from_kind(&manifest.header.key_provider);
        let mut trace = KeyringTrace::default();
        let key =
            match self
                .provider
                .unwrap_data_key(subject, &manifest.wrapped_key, &manifest.header)
            {
                Ok(key) => key,
                Err(error) => {
                    trace.push(trace_event(
                        "unwrap",
                        provider,
                        subject,
                        generation,
                        Some(ProviderFailureKind::classify(&error)),
                    ));
                    return Err(map_key_provider_error(error));
                }
            };
        let provider = ProviderIdentity::from_kind(&manifest.header.key_provider);
        trace.push(trace_event(
            "unwrap",
            provider.clone(),
            subject,
            generation,
            None,
        ));
        let commitment =
            CommitmentMetadata::new(&manifest.header, &manifest.wrapped_key, generation);
        Ok(CryptoMaterials {
            suite: AlgorithmSuite::from_manifest_cipher(expected_cipher),
            template: DekTemplate::for_manifest_cipher(expected_cipher),
            subject_descriptor: subject.descriptor(),
            provider,
            commitment,
            manifest: manifest.clone(),
            trace,
            data_key: RevocableDataKey::new(key, subject, generation, self.shred_registry.clone()),
        })
    }
}

/// Result of destroying a wrapped DEK and tombstoning a subject.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct CryptoShredOutcome {
    pub tombstone_path: PathBuf,
    pub destroyed_wrapped_dek: bool,
    pub generation: u64,
}

/// Delete the wrapped DEK sidecar and mark the subject as crypto-shredded.
///
/// This deliberately does not scrub ciphertext bytes. Destroying the wrapped
/// DEK plus revoking stale handles is the crypto-shred primitive.
pub fn crypto_shred_subject(
    protected_path: &Path,
    registry: &Arc<CryptoShredRegistry>,
    subject: &LocalKeySubject,
) -> Result<CryptoShredOutcome> {
    let manifest_path = KeyManifest::manifest_path(protected_path);
    let destroyed_wrapped_dek = match fs::remove_file(&manifest_path) {
        Ok(()) => true,
        Err(error) if error.kind() == io::ErrorKind::NotFound => false,
        Err(error) => {
            return Err(Error::Internal(format!(
                "failed to delete wrapped DEK manifest {} during crypto-shred: {error}",
                manifest_path.display()
            )));
        }
    };
    let generation = registry.crypto_shred(subject);
    let tombstone_path = shred_tombstone_path(protected_path);
    if let Some(parent) = tombstone_path.parent() {
        fs::create_dir_all(parent).map_err(|error| {
            Error::Internal(format!(
                "failed to create crypto-shred tombstone parent {}: {error}",
                parent.display()
            ))
        })?;
    }
    let tombstone = format!(
        "nimbus-crypto-shred-v1\nsubject={}\ngeneration={generation}\ndestroyed_wrapped_dek={destroyed_wrapped_dek}\n",
        subject.descriptor()
    );
    fs::write(&tombstone_path, tombstone).map_err(|error| {
        Error::Internal(format!(
            "failed to write crypto-shred tombstone {}: {error}",
            tombstone_path.display()
        ))
    })?;
    Ok(CryptoShredOutcome {
        tombstone_path,
        destroyed_wrapped_dek,
        generation,
    })
}

pub fn shred_tombstone_path(protected_path: &Path) -> PathBuf {
    let mut path = KeyManifest::manifest_path(protected_path)
        .as_os_str()
        .to_owned();
    path.push(".shredded");
    PathBuf::from(path)
}

pub(crate) fn validate_manifest(
    manifest: &KeyManifest,
    provider: &dyn LocalKeyProvider,
    subject: &LocalKeySubject,
    expected_cipher: ManifestCipher,
    protected_path: &Path,
) -> Result<()> {
    let expected_descriptor = subject.descriptor();
    if manifest.header.subject_descriptor != expected_descriptor {
        return Err(Error::InvalidInput(format!(
            "encryption manifest for {} belongs to '{}' instead of '{}'",
            protected_path.display(),
            manifest.header.subject_descriptor,
            expected_descriptor
        )));
    }
    if manifest.header.cipher != expected_cipher {
        return Err(Error::InvalidInput(format!(
            "encryption manifest for {} expects '{}' but '{}' was requested",
            protected_path.display(),
            manifest.header.cipher.as_str(),
            expected_cipher.as_str()
        )));
    }
    let expected_provider = provider.kind();
    if manifest.header.key_provider != expected_provider {
        return Err(Error::InvalidInput(format!(
            "encryption manifest for {} was wrapped by '{}' but current config uses '{}'",
            protected_path.display(),
            manifest.header.key_provider,
            expected_provider
        )));
    }
    Ok(())
}

pub(crate) fn map_key_provider_error(error: LocalKeyProviderError) -> Error {
    match error {
        LocalKeyProviderError::MasterKeyReadError { path, source } => {
            if source.kind() == io::ErrorKind::NotFound {
                Error::InvalidInput(format!("master key file not found: {}", path.display()))
            } else if source.kind() == io::ErrorKind::PermissionDenied {
                Error::PermissionDenied(format!(
                    "cannot read master key file (check permissions): {}",
                    path.display()
                ))
            } else {
                Error::Internal(format!(
                    "failed to read master key file {}: {source}",
                    path.display()
                ))
            }
        }
        LocalKeyProviderError::InvalidMasterKeySize { path, actual } => {
            Error::InvalidInput(format!(
                "master key file {} must contain exactly 32 bytes, found {actual}",
                path.display()
            ))
        }
        LocalKeyProviderError::KeyDirectoryReadError { path, source } => {
            if source.kind() == io::ErrorKind::PermissionDenied {
                Error::PermissionDenied(format!(
                    "cannot read key directory entry (check permissions): {}",
                    path.display()
                ))
            } else {
                Error::Internal(format!(
                    "failed to read key directory entry {}: {source}",
                    path.display()
                ))
            }
        }
        LocalKeyProviderError::KeyFileNotFound { path } => {
            Error::InvalidInput(format!("key file not found: {}", path.display()))
        }
        LocalKeyProviderError::InvalidKeyFileSize { path, actual } => Error::InvalidInput(format!(
            "key file {} must contain exactly 32 bytes, found {actual}",
            path.display()
        )),
        LocalKeyProviderError::AwsKmsKeyNotFound { key_id } => {
            Error::InvalidInput(format!("aws kms key not found: {key_id}"))
        }
        LocalKeyProviderError::AwsKmsConfigurationError { message } => {
            Error::InvalidInput(format!("aws kms configuration error: {message}"))
        }
        LocalKeyProviderError::AwsKmsAuthError { message }
        | LocalKeyProviderError::AwsKmsPermissionDenied { message, .. } => {
            Error::PermissionDenied(message)
        }
        LocalKeyProviderError::AwsKmsNetworkError { operation, message } => Error::Internal(
            format!("aws kms network error during {operation}: {message}"),
        ),
        LocalKeyProviderError::AwsKmsOperationError { operation, message } => {
            Error::Internal(format!("aws kms {operation} failed: {message}"))
        }
        LocalKeyProviderError::UnwrapError { message } => Error::PermissionDenied(message),
        LocalKeyProviderError::WrapError { message }
        | LocalKeyProviderError::UnsupportedCipher { cipher: message }
        | LocalKeyProviderError::RandomError { message } => Error::Internal(message),
    }
}

fn map_shred_error(error: CryptoShredError) -> Error {
    Error::PermissionDenied(error.to_string())
}

fn key_manifest_header(
    subject: &LocalKeySubject,
    key_provider: KeyProviderKind,
    cipher: ManifestCipher,
) -> KeyManifestHeader {
    let now = SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .map(|duration| duration.as_secs())
        .unwrap_or(0);
    KeyManifestHeader {
        version: MANIFEST_VERSION,
        cipher,
        subject_descriptor: subject.descriptor(),
        key_provider,
        created_at: now,
        rotated_at: now,
    }
}

fn trace_event(
    action: &'static str,
    provider: ProviderIdentity,
    subject: &LocalKeySubject,
    generation: u64,
    provider_failure: Option<ProviderFailureKind>,
) -> KeyringTraceEvent {
    let mut digest = Sha256::new();
    digest.update(subject.descriptor().as_bytes());
    KeyringTraceEvent {
        action,
        provider,
        subject_hash: digest.finalize().into(),
        generation,
        provider_failure,
    }
}

