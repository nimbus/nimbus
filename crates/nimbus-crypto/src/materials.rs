/// Shared generation/tombstone state for revocable crypto material handles.
#[derive(Debug, Default)]
pub struct CryptoShredRegistry {
    subjects: Mutex<BTreeMap<String, SubjectShredState>>,
}

#[derive(Debug, Clone, Copy, Default)]
struct SubjectShredState {
    generation: u64,
    tombstoned: bool,
}

impl CryptoShredRegistry {
    pub fn new() -> Self {
        Self::default()
    }

    fn acquire_generation(
        &self,
        subject: &LocalKeySubject,
    ) -> std::result::Result<u64, CryptoShredError> {
        let descriptor = subject.descriptor();
        let subjects = self
            .subjects
            .lock()
            .expect("crypto-shred registry lock should be available");
        let state = subjects.get(&descriptor).copied().unwrap_or_default();
        if state.tombstoned {
            Err(CryptoShredError::SubjectTombstoned { descriptor })
        } else {
            Ok(state.generation)
        }
    }

    fn assert_live(
        &self,
        descriptor: &str,
        handle_generation: u64,
    ) -> std::result::Result<(), CryptoShredError> {
        let subjects = self
            .subjects
            .lock()
            .expect("crypto-shred registry lock should be available");
        let state = subjects.get(descriptor).copied().unwrap_or_default();
        if state.tombstoned || state.generation != handle_generation {
            return Err(CryptoShredError::StaleHandle {
                descriptor: descriptor.to_string(),
                handle_generation,
                current_generation: state.generation,
            });
        }
        Ok(())
    }

    fn crypto_shred(&self, subject: &LocalKeySubject) -> u64 {
        let descriptor = subject.descriptor();
        let mut subjects = self
            .subjects
            .lock()
            .expect("crypto-shred registry lock should be available");
        let state = subjects.entry(descriptor).or_default();
        state.generation = state.generation.saturating_add(1);
        state.tombstoned = true;
        state.generation
    }
}

/// Errors produced when a revocable DEK handle is used after crypto-shred.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum CryptoShredError {
    SubjectTombstoned {
        descriptor: String,
    },
    StaleHandle {
        descriptor: String,
        handle_generation: u64,
        current_generation: u64,
    },
}

impl fmt::Display for CryptoShredError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::SubjectTombstoned { descriptor } => {
                write!(f, "crypto-shred tombstone exists for {descriptor}")
            }
            Self::StaleHandle {
                descriptor,
                handle_generation,
                current_generation,
            } => write!(
                f,
                "stale crypto handle for {descriptor}: handle generation {handle_generation}, current generation {current_generation}"
            ),
        }
    }
}

impl std::error::Error for CryptoShredError {}

/// Revocable plaintext DEK handle.
pub struct RevocableDataKey {
    key: DataEncryptionKey,
    subject_descriptor: String,
    generation: u64,
    registry: Arc<CryptoShredRegistry>,
}

impl RevocableDataKey {
    fn new(
        key: DataEncryptionKey,
        subject: &LocalKeySubject,
        generation: u64,
        registry: Arc<CryptoShredRegistry>,
    ) -> Self {
        Self {
            key,
            subject_descriptor: subject.descriptor(),
            generation,
            registry,
        }
    }

    pub fn as_bytes(&self) -> std::result::Result<&[u8; 32], CryptoShredError> {
        self.registry
            .assert_live(&self.subject_descriptor, self.generation)?;
        Ok(self.key.as_bytes())
    }

    pub(crate) fn into_data_key(self) -> std::result::Result<DataEncryptionKey, CryptoShredError> {
        self.registry
            .assert_live(&self.subject_descriptor, self.generation)?;
        Ok(self.key)
    }
}

impl fmt::Debug for RevocableDataKey {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.debug_struct("RevocableDataKey")
            .field("subject_descriptor", &"[REDACTED]")
            .field("generation", &self.generation)
            .field("plaintext", &"[REDACTED]")
            .finish()
    }
}

