/// The accepted envelope algorithm suite for persisted subject data.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum AlgorithmSuite {
    /// Version-1 local envelope encryption with a random 256-bit DEK.
    LocalEnvelopeV1 { cipher: ManifestCipher },
}

impl AlgorithmSuite {
    pub fn from_manifest_cipher(cipher: ManifestCipher) -> Self {
        Self::LocalEnvelopeV1 { cipher }
    }

    pub fn manifest_cipher(self) -> ManifestCipher {
        match self {
            Self::LocalEnvelopeV1 { cipher } => cipher,
        }
    }
}

/// Template for data-encryption keys generated by the envelope keyring.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct DekTemplate {
    pub suite: AlgorithmSuite,
    pub key_bytes: usize,
}

impl DekTemplate {
    pub fn for_manifest_cipher(cipher: ManifestCipher) -> Self {
        Self {
            suite: AlgorithmSuite::from_manifest_cipher(cipher),
            key_bytes: 32,
        }
    }
}

/// Non-secret commitment metadata for an envelope operation.
#[derive(Clone, PartialEq, Eq)]
pub struct CommitmentMetadata {
    pub manifest_aad_sha256: [u8; 32],
    pub wrapped_key_bytes: usize,
    pub subject_generation: u64,
}

impl CommitmentMetadata {
    fn new(header: &KeyManifestHeader, wrapped: &WrappedDataKey, subject_generation: u64) -> Self {
        let mut digest = Sha256::new();
        digest.update(header.to_aad());
        Self {
            manifest_aad_sha256: digest.finalize().into(),
            wrapped_key_bytes: wrapped.ciphertext.len(),
            subject_generation,
        }
    }
}

impl fmt::Debug for CommitmentMetadata {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.debug_struct("CommitmentMetadata")
            .field("manifest_aad_sha256", &"[REDACTED_DIGEST]")
            .field("wrapped_key_bytes", &self.wrapped_key_bytes)
            .field("subject_generation", &self.subject_generation)
            .finish()
    }
}

/// Provider family used for stable audit and error mapping.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ProviderFamily {
    MasterKeyFile,
    KeyDirectory,
    AwsKms,
}

/// Diagnostics-safe provider identity.
#[derive(Clone, PartialEq, Eq)]
pub struct ProviderIdentity {
    pub family: ProviderFamily,
    pub key_id_hint: Option<String>,
    pub region: Option<String>,
}

impl ProviderIdentity {
    pub fn from_kind(kind: &KeyProviderKind) -> Self {
        match kind {
            KeyProviderKind::MasterKeyFile { .. } => Self {
                family: ProviderFamily::MasterKeyFile,
                key_id_hint: None,
                region: None,
            },
            KeyProviderKind::KeyDirectory { .. } => Self {
                family: ProviderFamily::KeyDirectory,
                key_id_hint: None,
                region: None,
            },
            KeyProviderKind::AwsKms { key_id, region } => Self {
                family: ProviderFamily::AwsKms,
                key_id_hint: Some(redacted_key_hint(key_id)),
                region: region.clone(),
            },
        }
    }
}

impl fmt::Debug for ProviderIdentity {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.debug_struct("ProviderIdentity")
            .field("family", &self.family)
            .field("key_id_hint", &self.key_id_hint)
            .field("region", &self.region)
            .field("secret", &"[REDACTED]")
            .finish()
    }
}

fn redacted_key_hint(key_id: &str) -> String {
    let suffix: String = key_id
        .chars()
        .rev()
        .take(8)
        .collect::<String>()
        .chars()
        .rev()
        .collect();
    format!("...{suffix}")
}

/// Stable provider failure classes before errors cross crate boundaries.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ProviderFailureKind {
    WrongProvider,
    BadKey,
    DeniedDecrypt,
    InvalidCredentials,
    NetworkFailure,
    EndpointOrTls,
    Randomness,
    Io,
    Unknown,
}

impl ProviderFailureKind {
    pub fn classify(error: &LocalKeyProviderError) -> Self {
        match error {
            LocalKeyProviderError::UnsupportedCipher { .. } => Self::WrongProvider,
            LocalKeyProviderError::UnwrapError { .. }
            | LocalKeyProviderError::AwsKmsKeyNotFound { .. }
            | LocalKeyProviderError::KeyFileNotFound { .. }
            | LocalKeyProviderError::InvalidKeyFileSize { .. }
            | LocalKeyProviderError::InvalidMasterKeySize { .. } => Self::BadKey,
            LocalKeyProviderError::AwsKmsPermissionDenied { .. } => Self::DeniedDecrypt,
            LocalKeyProviderError::AwsKmsAuthError { .. }
            | LocalKeyProviderError::AwsKmsConfigurationError { .. } => Self::InvalidCredentials,
            LocalKeyProviderError::AwsKmsNetworkError { message, .. } => {
                if message.to_ascii_lowercase().contains("endpoint")
                    || message.to_ascii_lowercase().contains("tls")
                {
                    Self::EndpointOrTls
                } else {
                    Self::NetworkFailure
                }
            }
            LocalKeyProviderError::RandomError { .. } => Self::Randomness,
            LocalKeyProviderError::MasterKeyReadError { .. }
            | LocalKeyProviderError::KeyDirectoryReadError { .. } => Self::Io,
            LocalKeyProviderError::WrapError { .. }
            | LocalKeyProviderError::AwsKmsOperationError { .. } => Self::Unknown,
        }
    }
}

