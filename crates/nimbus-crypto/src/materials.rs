    #[test]
    fn crypto_shred_deletes_wrapped_dek_and_revokes_pre_shred_handle() {
        let dir = tempdir().expect("tempdir should create");
        let key_path = dir.path().join("master.key");
        write_test_key(&key_path);
        let provider = MasterKeyFileProvider::new(key_path).expect("provider should create");
        let registry = Arc::new(CryptoShredRegistry::new());
        let keyring = EnvelopeKeyring::with_shred_registry(&provider, registry.clone());
        let subject = test_subject();
        let protected_path = dir.path().join("demo.sqlite3");
        fs::write(&protected_path, b"ciphertext").expect("protected bytes should write");
        let materials = keyring
            .generate_materials(&subject, ManifestCipher::SqlCipher)
            .expect("materials should generate");
        materials
            .manifest
            .write_for(&protected_path)
            .expect("manifest should write");
        let pre_shred_key = materials
            .data_key_bytes()
            .expect("pre-shred key should be live")
            .to_vec();

        let outcome = crypto_shred_subject(&protected_path, &registry, &subject)
            .expect("crypto-shred should complete");

        assert!(outcome.destroyed_wrapped_dek);
        assert!(outcome.tombstone_path.exists());
        assert!(!KeyManifest::manifest_path(&protected_path).exists());
        assert_eq!(
            materials
                .data_key_bytes()
                .expect_err("pre-shred handle should fail after shred"),
            CryptoShredError::StaleHandle {
                descriptor: subject.descriptor(),
                handle_generation: 0,
                current_generation: 1,
            }
        );
        assert_eq!(pre_shred_key.len(), 32);

        let reopen_result = keyring.open_materials(
            &materials.manifest,
            &subject,
            ManifestCipher::SqlCipher,
            &protected_path,
        );
        assert!(matches!(reopen_result, Err(Error::PermissionDenied(_))));
    }

